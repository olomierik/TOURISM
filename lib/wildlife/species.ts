const BY_SLUG = new Map(SPECIES.map((s) => [s.slug, s]));

export function getSpecies(slug: string): Species | undefined {
  return BY_SLUG.get(slug);
}

/** What the grid needs — small enough to hand to the browser for filtering. */
export type SpeciesCardData = Pick<
  Species,
  'slug' | 'name' | 'scientific' | 'group' | 'bigFive' | 'iucn' | 'rarity'
> & { image: string | null; hasCall: boolean };

export function toCard(s: Species): SpeciesCardData {
  return {
    slug: s.slug,
    name: s.name,
    scientific: s.scientific,
    group: s.group,
    bigFive: s.bigFive,
    iucn: s.iucn,
    rarity: s.rarity,
    // Commons serves only its standard widths (250, 330, 500, 960, 1280…);
    // 500 is plenty for a card.
    image: s.image ? s.image.url.replace(/\/1280px-/, '/500px-') : null,
    hasCall: s.call !== null,
  };
}

export const BIG_FIVE = SPECIES.filter((s) => s.bigFive);
